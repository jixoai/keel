// Media families this wiring understands. They match modelcfg's provider type
// vocabulary and mediaadapter's Error/Usage family ids.
const (
	FamilyImage    = "image"
	FamilyVideo    = "video"
	FamilyTTS      = "tts"
	FamilySTT      = "stt"
	FamilyDecision = "decision"
)

// familyOrder is the stable order tools are appended to the host registry.
var familyOrder = []string{FamilyImage, FamilyVideo, FamilyTTS, FamilySTT, FamilyDecision}

// Options is one tenant document plus the hosting process's credential and
// artifact seams.
type Options struct {
	// Models is the tenant models document (models slice). Empty means no
	// provider configuration: every family is absent.
	Models json.RawMessage
	// Legacy is the flat agent configuration the modelcfg overlay normalizes
	// when the document declares no providers/rules. Media providers are only
	// reachable through the document (the flat config has no family), but it is
	// passed through so resolution is byte-for-byte the llm service's.
	Legacy modelcfg.LegacyAgent
	// Credential resolves one provider access declaration. The second return is
	// the operator-readable reason no credential exists (empty on success); it
	// never carries a value. A nil resolver treats every api-key provider as
	// missing a credential.
	Credential func(modelcfg.Access) (string, string)
	// Artifacts is the process-wide layerfs store generated bytes are written
	// to. Nil means this deployment has no artifact store: no media tool is
	// wired (a result reference nobody can resolve is worse than no tool).
	Artifacts *layerfs.Store
	// NextSeq supplies layerfs retention sequence numbers. Nil falls back to the
	// time-seeded counter inside mediaadapter.LayerFSStore (safe for a tool call
	// with no ledger event of its own).
	NextSeq func(context.Context) (int64, error)
	// HTTPClient is the provider client. Nil uses mediaadapter.BoundedHTTPClient.
	HTTPClient *http.Client
	// Fetcher downloads provider-returned asset URLs. Nil uses a bounded HTTP
	// fetcher with the same MaxAssetBytes bound.
	Fetcher mediaadapter.AssetFetcher
	// MaxAssetBytes bounds one generated asset. Zero uses mediaadapter's default.
	MaxAssetBytes int64
	// validateOnly is set by ValidateModels: the settings save path checks the
	// provider/decision shape, not whether this process happens to hold the
	// artifact seam (which it always does when serving).
	validateOnly bool
}

// FamilyState is one family's assembly fact, for logs and tests. It is not a
// model-facing value.
type FamilyState struct {
	Family     string `json:"family"`
	Configured bool   `json:"configured"`
	Wired      bool   `json:"wired"`
	ProviderID string `json:"providerId,omitempty"`
	ModelID    string `json:"modelId,omitempty"`
	Reason     string `json:"reason,omitempty"`
}

// Result is one assembly: the tools to append to the host registry, the
// provider-scoped issues the settings write path renders, and the per-family
// state.
type Result struct {
	Tools    []agentcore.AgentTool
	Issues   []modelcfg.Issue
	Families map[string]FamilyState
}

// Wired reports whether a family has a runtime surface.
func (r Result) Wired(family string) bool {
	state, ok := r.Families[family]
	return ok && state.Wired
}

// Build resolves the tenant document and assembles every media family it
// declares. A malformed document is a Result carrying one document issue rather
// than a panic: the settings path already refused it, and the host must not
// guess.
func Build(opts Options) Result {
	result := Result{Families: map[string]FamilyState{}}
	resolved, err := resolve(opts)
	if err != nil {
		result.Issues = append(result.Issues, modelcfg.Issue{Field: "document", Message: err.Error()})
		for _, family := range familyOrder {
			result.Families[family] = FamilyState{Family: family, Reason: err.Error()}
		}
		return result
	}
	for _, family := range familyOrder {
		result.Families[family] = FamilyState{Family: family}
	}

	// Decision validation is independent of a runtime tool: it is the settings
	// save path's preflight and the boot-time diagnostic.
	decisionIssues := validateDecision(resolved)
	result.Issues = append(result.Issues, decisionIssues...)
	if candidate, ok := chooseModel(resolved, FamilyDecision); ok {
		state := result.Families[FamilyDecision]
		state.Configured = true
		state.ProviderID, state.ModelID = candidate.provider.ProviderID, candidate.model.ModelID
		state.Reason = "decision providers are validated at settings save; no agent tool calls them yet"
		for _, issue := range decisionIssues {
			if strings.HasPrefix(issue.Field, providerField(candidate.provider.ProviderID)) {
				state.Reason = issue.Message
				break
			}
		}
		result.Families[FamilyDecision] = state
	}

	imageTool, imageState, imageIssues := buildImageTool(resolved, opts)
	result.Issues = append(result.Issues, imageIssues...)
	result.Families[FamilyImage] = imageState
	if imageTool != nil {
		result.Tools = append(result.Tools, imageTool)
	}

	videoTool, videoState, videoIssues := buildVideoTool(resolved, opts)
	result.Issues = append(result.Issues, videoIssues...)
	result.Families[FamilyVideo] = videoState
	if videoTool != nil {
		result.Tools = append(result.Tools, videoTool)
	}

	// Speech is deliberately library-only for now: detect it so the state says
	// "configured, not wired" instead of pretending the capability exists.
	for _, family := range []string{FamilyTTS, FamilySTT} {
		if candidate, ok := chooseModel(resolved, family); ok {
			state := result.Families[family]
			state.Configured = true
			state.ProviderID, state.ModelID = candidate.provider.ProviderID, candidate.model.ModelID
			state.Reason = "speech adapter is library-only: no host tool or /v1/media surface is wired yet"
			result.Families[family] = state
		}
	}

	sortIssues(result.Issues)
	return result
}

// ValidateModels is the settings save path's media/decision check. It runs the
// same resolution and decision preflight Build runs; the artifact/tool seam is
// irrelevant to validation and may be nil.
func ValidateModels(opts Options) []modelcfg.Issue {
	opts.validateOnly = true
	return Build(opts).Issues
}

type resolved struct {
	resolution modelcfg.Resolution
	selection  modelcfg.Selection
}

func resolve(opts Options) (resolved, error) {
	overlay, err := modelcfg.OverlayFromDocument(opts.Models, opts.Legacy)
	if err != nil {
		return resolved{}, err
	}
	resolver, err := modelcfg.NewResolver(modelcfg.DemoCatalogFromEnv(), overlay)
	if err != nil {
		return resolved{}, err
	}
	return resolved{resolution: resolver.Resolve(), selection: overlay.Selection()}, nil
}

type modelCandidate struct {
	provider modelcfg.ProviderView
	model    modelcfg.ModelView
}

// chooseModel picks the provider/model a family tool uses. The rule is the
// tenant's default selection when it names a model of that family (the same
// default every attempt resolves), otherwise the first family model in
// resolution order. Selection is never taken from the model: the tool schema
// has no model argument.
func chooseModel(resolved resolved, family string) (modelCandidate, bool) {
	if resolved.selection.ProviderID != "" || resolved.selection.ModelID != "" {
		if candidate, ok := findModel(resolved, family, resolved.selection.ProviderID, resolved.selection.ModelID); ok {
			return candidate, true
		}
	}
	for _, provider := range resolved.resolution.Providers {
		if provider.API.Type == modelcfg.APITypeDemo {
			continue
		}
		for _, model := range provider.Models {
			if model.ProviderType == family && model.Enabled {
				return modelCandidate{provider: provider, model: model}, true
			}
		}
	}
	return modelCandidate{}, false
}

func findModel(resolved resolved, family, providerID, modelID string) (modelCandidate, bool) {
	for _, provider := range resolved.resolution.Providers {
		if providerID != "" && provider.ProviderID != providerID {
			continue
		}
		for _, model := range provider.Models {
			if modelID != "" && model.ModelID != modelID {
				continue
			}
			if model.ProviderType == family && model.Enabled {
				return modelCandidate{provider: provider, model: model}, true
			}
		}
	}
	return modelCandidate{}, false
}

func providerField(providerID string) string {
	return "providers[" + providerID + "]"
}

func sortIssues(issues []modelcfg.Issue) {
	sort.SliceStable(issues, func(i, j int) bool {
		if issues[i].Field == issues[j].Field {
			return issues[i].Message < issues[j].Message
		}
		return issues[i].Field < issues[j].Field
	})
}

func issue(providerID, field, message string) modelcfg.Issue {
	return modelcfg.Issue{Field: providerField(providerID) + "." + field, Message: message}
}

// credential resolves a provider's credential. A credential-free provider is
// complete with the empty key; an api-key provider with no value fails closed
// with the reason the settings view already shows.
func credential(opts Options, provider modelcfg.ProviderView) (string, string) {
	if provider.Access.CredentialFree() {
		return "", ""
	}
	if opts.Credential == nil {
		return "", "no credential resolver is configured"
	}
	value, reason := opts.Credential(provider.Access)
	if reason != "" {
		return "", reason
	}
	if strings.TrimSpace(value) == "" {
		return "", "provider has no credential; refusing an unauthenticated request"
	}
	return value, ""
}

// failingImageProvider is the fail-closed stand-in for a configured image
// provider whose credential could not be resolved. It never touches the wire.
type failingImageProvider struct {
	reason string
}

func (p *failingImageProvider) GenerateImage(context.Context, mediaadapter.ImageRequest) (mediaadapter.ImageBatch, error) {
	return mediaadapter.ImageBatch{}, missingCredential(FamilyImage, p.reason)
}

type failingVideoProvider struct {
	reason string
}

func (p *failingVideoProvider) GenerateVideo(context.Context, mediaadapter.VideoRequest) (mediaadapter.VideoBatch, error) {
	return mediaadapter.VideoBatch{}, missingCredential(FamilyVideo, p.reason)
}

func missingCredential(family, reason string) *mediaadapter.Error {
	if strings.TrimSpace(reason) == "" {
		reason = "provider has no credential; refusing an unauthenticated request"
	}
	return &mediaadapter.Error{
		Family:  family,
		Op:      "generate",
		Kind:    mediaadapter.KindMissingCredentials,
		Message: reason,
	}
}

// store builds the layerfs artifact store shared by every media family.
func store(opts Options) mediaadapter.ArtifactStore {
	if opts.Artifacts == nil {
		return nil
	}
	return &mediaadapter.LayerFSStore{Store: opts.Artifacts, NextSeq: opts.NextSeq}
}

func fetcher(opts Options) mediaadapter.AssetFetcher {
	if opts.Fetcher != nil {
		return opts.Fetcher
	}
	return mediaadapter.NewHTTPFetcher(opts.MaxAssetBytes)
}

func httpClient(opts Options) *http.Client {
	if opts.HTTPClient != nil {
		return opts.HTTPClient
	}
	return mediaadapter.BoundedHTTPClient(0)
}

func buildImageTool(resolved resolved, opts Options) (agentcore.AgentTool, FamilyState, []modelcfg.Issue) {
	state := FamilyState{Family: FamilyImage}
	candidate, ok := chooseModel(resolved, FamilyImage)
	if !ok {
		return nil, state, nil
	}
	state.Configured = true
	state.ProviderID, state.ModelID = candidate.provider.ProviderID, candidate.model.ModelID
	if opts.Artifacts == nil && !opts.validateOnly {
		state.Reason = "no artifact store: generated images could not be referenced"
		return nil, state, []modelcfg.Issue{issue(candidate.provider.ProviderID, "media.artifacts",
			"this deployment has no artifact store, so image generation cannot return a layerfs reference")}
	}
	if strings.TrimSpace(candidate.provider.API.BaseURL) == "" {
		state.Reason = "provider has no base URL"
		return nil, state, []modelcfg.Issue{issue(candidate.provider.ProviderID, "api.baseUrl", "base URL is required")}
	}
	key, reason := credential(opts, candidate.provider)
	var provider mediaadapter.ImageProvider
	if reason != "" {
		state.Reason = reason
		provider = &failingImageProvider{reason: reason}
	} else {
		wire, err := mediaadapter.NewHTTPImageProvider(mediaadapter.HTTPImageConfig{
			BaseURL: candidate.provider.API.BaseURL,
			APIKey:  key,
			Model:   candidate.model.ModelID,
			Client:  httpClient(opts),
		})
		if err != nil {
			state.Reason = err.Error()
			return nil, state, []modelcfg.Issue{issue(candidate.provider.ProviderID, "media.image", err.Error())}
		}
		provider = wire
	}
	adapter := &mediaadapter.ImageAdapter{
		Provider:      provider,
		Store:         store(opts),
		Fetcher:       fetcher(opts),
		MaxAssetBytes: opts.MaxAssetBytes,
	}
	state.Wired = true
	state.Reason = ""
	return mediaadapter.NewImageTool(adapter), state, nil
}

