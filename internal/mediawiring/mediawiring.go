// Summary renders one line per family for a boot log or an evidence run.
func (r Result) Summary() string {
	return summary(r)
}

func summary(result Result) string {
	parts := make([]string, 0, len(familyOrder))
	for _, family := range familyOrder {
		state := result.Families[family]
		switch {
		case state.Wired:
			parts = append(parts, fmt.Sprintf("%s=%s/%s", family, state.ProviderID, state.ModelID))
		case state.Configured:
			parts = append(parts, family+"=configured(not wired)")
		}
	}
	return strings.Join(parts, " ")
}
