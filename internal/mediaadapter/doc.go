// Package mediaadapter is the agent-facing adapter layer for the media
// provider families: image generation, video generation, speech synthesis and
// transcription, and structured decisions.
//
// # Position in the stack
//
// internal/mediagw is the human/UI-facing gateway: it owns one deployment-wide
// credential from the environment and serves /v1/media/*. This package is the
// other half: one adapter per configured provider/model, callable by an agent
// turn (image_generate / video_generate tool shapes), by a CLI surface, or by a
// gate that needs a typed decision. It never reads a process-wide credential;
// the caller injects the resolved endpoint and key, so a tenant's provider
// configuration stays the routing authority.
//
// internal/provider's Provider interface is deliberately not reused here. It
// is a streaming chat contract (CompletionRequest -> text/tool events); a
// decision model is not a chat model (spec decision-provider: no messages, no
// free text), and image/video/audio are request/response assets rather than
// token streams. Forcing those families through the chat contract would fake
// text that the provider never produced. This package therefore declares the
// capability-specific interfaces the families actually need.
//
// # Invariants
//
//   - Generated bytes are written to an ArtifactStore (backed by layerfs in a
//     deployment). Results and events carry only Artifact references (blob id,
//     size, mime, dimensions); base64 never enters a tool result or an event.
//   - Usage records objective counts only (tokens, items, bytes, characters,
//     milliseconds). No price, cost or currency field exists in this package,
//     and an upstream cost field is dropped instead of forwarded.
//   - A provider failure is a typed error, not a fabricated default. Decision
//     failures never become noul:0 / choice:"unknown" / confidence:0; the
//     default policy is fail-closed. Shadow policy records the failure and
//     returns no answer, which is the only permitted fail-open path.
//   - A provider panic is recovered at the adapter boundary and reported as a
//     retryable provider_unavailable error. It cannot take down the harness or
//     another provider.
//   - Request validation happens before the wire call, and a failed request
//     keeps its input (prompt/parameters) in the tool error envelope so the
//     call can be retried without reconstructing it.
package mediaadapter
