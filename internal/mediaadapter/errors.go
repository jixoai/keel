package mediaadapter

import (
	"context"
	"errors"
	"fmt"
	"strings"
)

// ErrorKind classifies an adapter failure without exposing provider internals.
type ErrorKind string

const (
	// KindConfig is a deployment/assembly problem: no provider, no store, a bad
	// base URL. It is not retryable by the caller.
	KindConfig ErrorKind = "config"
	// KindRequest is a malformed call (empty prompt, unsupported question type,
	// remote image URL). It is not retryable without changing the input.
	KindRequest ErrorKind = "invalid_request"
	// KindMissingCredentials is a provider with no usable credential. The adapter
	// does not attempt an unauthenticated request.
	KindMissingCredentials ErrorKind = "missing_credentials"
	// KindUpstream is a provider response that is non-2xx or violates the wire
	// contract.
	KindUpstream ErrorKind = "upstream_error"
	// KindTimeout is a context deadline or client timeout.
	KindTimeout ErrorKind = "timeout"
	// KindProviderUnavailable is a recovered provider panic or transport failure.
	// The attempt may be retried.
	KindProviderUnavailable ErrorKind = "provider_unavailable"
	// KindArtifact is a failure to persist generated bytes. The provider call may
	// have succeeded; retrying is safe for deterministic providers.
	KindArtifact ErrorKind = "artifact_error"
)

// FieldError locates one invalid input at a field path. Paths are stable enough
// for a settings form to highlight the exact control ("questions.urgent.type").
type FieldError struct {
	Field   string `json:"field"`
	Message string `json:"message"`
}

// Error is the adapter's typed failure. Message is sanitized: it never carries
// the credential, and upstream bodies are bounded and scrubbed.
type Error struct {
	Family    string       `json:"family"`
	Op        string       `json:"op"`
	Kind      ErrorKind    `json:"kind"`
	Status    int          `json:"status,omitempty"`
	Message   string       `json:"message"`
	Retryable bool         `json:"retryable"`
	Fields    []FieldError `json:"fields,omitempty"`
	Err       error        `json:"-"`
}

func (e *Error) Error() string {
	if e == nil {
		return "<nil>"
	}
	parts := make([]string, 0, 3)
	if e.Family != "" {
		parts = append(parts, e.Family)
	}
	if e.Op != "" {
		parts = append(parts, e.Op)
	}
	prefix := strings.Join(parts, ".")
	if prefix == "" {
		prefix = "mediaadapter"
	}
	if e.Message == "" {
		return prefix
	}
	return prefix + ": " + e.Message
}

func (e *Error) Unwrap() error { return e.Err }

// ErrDecisionUnavailable is the fail-closed decision sentinel. An enforced
// decision that cannot be obtained wraps it; callers must block the action.
var ErrDecisionUnavailable = errors.New("mediaadapter: decision unavailable")

// Is makes errors.Is(err, ErrDecisionUnavailable) true for an enforced
// provider failure without pretending the same error kind means "unavailable"
// in another family.
func (e *Error) Is(target error) bool {
	return target == ErrDecisionUnavailable &&
		e.Family == FamilyDecision &&
		(e.Kind == KindProviderUnavailable || e.Kind == KindTimeout || e.Kind == KindUpstream)
}

// Family names used in Error and Usage. They match modelprovider's family ids.
const (
	FamilyImage    = "image"
	FamilyVideo    = "video"
	FamilyTTS      = "tts"
	FamilySTT      = "stt"
	FamilyDecision = "decision"
)

func configError(family, op, message string) *Error {
	return &Error{Family: family, Op: op, Kind: KindConfig, Message: message}
}

func requestError(family, op, message string, fields []FieldError) *Error {
	return &Error{Family: family, Op: op, Kind: KindRequest, Message: message, Fields: fields}
}

func artifactError(family, op string, err error) *Error {
	return &Error{
		Family:    family,
		Op:        op,
		Kind:      KindArtifact,
		Message:   "generated bytes could not be stored: " + err.Error(),
		Retryable: true,
		Err:       err,
	}
}

// upstreamError builds a sanitized provider failure. key is scrubbed from the
// message in case an upstream echoes request headers into its error body.
func upstreamError(family, op string, status int, message, key string) *Error {
	retryable := status == 0 || status == 408 || status == 429 || status >= 500
	if status == 0 {
		// A transport error (connection reset, DNS failure) is retryable.
		retryable = true
	}
	return &Error{
		Family:    family,
		Op:        op,
		Kind:      KindUpstream,
		Status:    status,
		Message:   sanitize(message, key),
		Retryable: retryable,
	}
}

// sanitize bounds and redacts an upstream message before it can reach a log, an
// event or a model. It is intentionally lossy: details live upstream.
func sanitize(message, secret string) string {
	message = strings.TrimSpace(message)
	if secret != "" {
		message = strings.ReplaceAll(message, secret, "[redacted]")
	}
	message = strings.Join(strings.Fields(message), " ")
	if len(message) > 512 {
		message = message[:512] + "…"
	}
	if message == "" {
		return "provider request failed"
	}
	return message
}

// providerError wraps a raw provider/transport error as a typed adapter error.
func providerError(family, op string, err error) *Error {
	if err == nil {
		return nil
	}
	var adapterErr *Error
	if errors.As(err, &adapterErr) {
		return adapterErr
	}
	kind := KindUpstream
	message := err.Error()
	if errors.Is(err, context.DeadlineExceeded) || strings.Contains(strings.ToLower(message), "timeout") {
		kind = KindTimeout
	}
	return &Error{
		Family:    family,
		Op:        op,
		Kind:      kind,
		Message:   sanitize(message, ""),
		Retryable: true,
		Err:       err,
	}
}

// guard runs one provider call and converts a panic into a typed provider
// failure. Provider plugins are independent failure domains (spec
// provider-registry: a provider crash MUST NOT take down the harness or another
// provider); recovering here is the process-local half of that boundary.
func guard[T any](family, op string, call func() (T, error)) (out T, err error) {
	defer func() {
		if recovered := recover(); recovered != nil {
			var zero T
			out = zero
			err = &Error{
				Family:    family,
				Op:        op,
				Kind:      KindProviderUnavailable,
				Message:   fmt.Sprintf("provider panicked: %v", recovered),
				Retryable: true,
			}
		}
	}()
	return call()
}

// fieldSummary renders a bounded, human-readable list of field errors. The
// full structured list still rides Error.Fields for a form to highlight.
func fieldSummary(fields []FieldError) string {
	if len(fields) == 0 {
		return ""
	}
	limit := len(fields)
	if limit > 3 {
		limit = 3
	}
	parts := make([]string, 0, limit+1)
	for _, field := range fields[:limit] {
		if field.Field == "" {
			parts = append(parts, field.Message)
			continue
		}
		parts = append(parts, field.Field+": "+field.Message)
	}
	if len(fields) > limit {
		parts = append(parts, fmt.Sprintf("and %d more", len(fields)-limit))
	}
	return strings.Join(parts, "; ")
}
