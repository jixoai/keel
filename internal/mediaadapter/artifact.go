// Artifact kinds. They are the vocabulary a result/event uses; the bytes stay
// in the artifact store.
const (
	ArtifactImage = "image"
	ArtifactVideo = "video"
	ArtifactAudio = "audio"
)

// Usage records objective, provider-reported or adapter-counted values only.
// There is deliberately no price, cost or currency field: pricing belongs to
// the contract side, and an upstream cost value is dropped at the adapter edge.
type Usage struct {
	InputTokens          int   `json:"inputTokens,omitempty"`
	OutputTokens         int   `json:"outputTokens,omitempty"`
	Questions            int   `json:"questions,omitempty"`
	Images               int   `json:"images,omitempty"`
	Videos               int   `json:"videos,omitempty"`
	InputCharacters      int   `json:"inputCharacters,omitempty"`
	TranscriptCharacters int   `json:"transcriptCharacters,omitempty"`
	AudioBytes           int64 `json:"audioBytes,omitempty"`
	AudioMillis          int64 `json:"audioMillis,omitempty"`
	Bytes                int64 `json:"bytes,omitempty"`
}

// Artifact is the durable reference a result or event stores. BlobID is the
// layerfs display form ("sha256:<hex>"); the bytes are never inline.
type Artifact struct {
	Kind           string `json:"kind"`
	BlobID         string `json:"blobId"`
	Mime           string `json:"mime"`
	Size           int64  `json:"size"`
	Width          int    `json:"width,omitempty"`
	Height         int    `json:"height,omitempty"`
	DurationMillis int64  `json:"durationMillis,omitempty"`
	Name           string `json:"name,omitempty"`
}

// ArtifactInput is one write. Session is the layerfs retention owner; the
// adapter never guesses it (a tool call reads it from the run scope).
type ArtifactInput struct {
	Session        string
	Kind           string
	Mime           string
	Data           []byte
	Width          int
	Height         int
	DurationMillis int64
	Name           string
}

// ArtifactStore persists generated bytes and returns their reference.
type ArtifactStore interface {
	Put(ctx context.Context, in ArtifactInput) (Artifact, error)
}

// LayerFSStore is the production ArtifactStore: it writes the bytes into the
// layerfs content-addressed store and records one retention reference for the
// session. NextSeq supplies the reference sequence (normally the event
// sequence the caller is about to commit); nil falls back to a time-seeded
// counter so a standalone call cannot leave an unreferenced object, and two
// process starts do not reuse the same (session, seq) pair.
type LayerFSStore struct {
	Store   *layerfs.Store
	NextSeq func(context.Context) (int64, error)

	fallback atomic.Int64
}

var (
	_ ArtifactStore = (*LayerFSStore)(nil)
	_ AssetFetcher  = (*HTTPFetcher)(nil)
)

// Put implements ArtifactStore.
func (s *LayerFSStore) Put(ctx context.Context, in ArtifactInput) (Artifact, error) {
	if s == nil || s.Store == nil {
		return Artifact{}, configError("artifact", "put", "layerfs store is not configured")
	}
	if strings.TrimSpace(in.Session) == "" {
		return Artifact{}, requestError("artifact", "put", "artifact session is required for retention", []FieldError{{
			Field: "session", Message: "the layerfs reference owner is missing",
		}})
	}
	if len(in.Data) == 0 {
		return Artifact{}, requestError("artifact", "put", "artifact bytes are empty", nil)
	}
	hash, size, err := s.Store.PutBytes(in.Data)
	if err != nil {
		return Artifact{}, artifactError("artifact", "put", err)
	}
	seq, err := s.seq(ctx)
	if err != nil {
		return Artifact{}, artifactError("artifact", "put", err)
	}
	if _, err := s.Store.Retain(hash, layerfs.Ref{Session: in.Session, Seq: seq}); err != nil {
		return Artifact{}, artifactError("artifact", "retain", err)
	}
	return Artifact{
		Kind:           in.Kind,
		BlobID:         hash.Prefixed(),
		Mime:           artifactMime(in.Kind, in.Mime),
		Size:           size,
		Width:          in.Width,
		Height:         in.Height,
		DurationMillis: in.DurationMillis,
		Name:           in.Name,
	}, nil
}

func (s *LayerFSStore) seq(ctx context.Context) (int64, error) {
	if s.NextSeq != nil {
		return s.NextSeq(ctx)
	}
	// Sequence 0 is a valid layerfs reference. The fallback is only for calls
	// with no ledger event; seeding it from the clock keeps two process starts
	// from reusing one (session, seq) and silently dropping a reference. A
	// deployment that commits media results supplies NextSeq.
	if s.fallback.Load() == 0 {
		s.fallback.CompareAndSwap(0, time.Now().UnixNano())
	}
	return s.fallback.Add(1), nil
}

func artifactMime(kind, mime string) string {
	if strings.TrimSpace(mime) != "" {
		return strings.TrimSpace(mime)
	}
	switch kind {
	case ArtifactImage:
		return "image/png"
	case ArtifactVideo:
		return "video/mp4"
	case ArtifactAudio:
		return "audio/wav"
	default:
		return "application/octet-stream"
	}
}

// FetchedAsset is the bytes of one provider-hosted asset.
type FetchedAsset struct {
	Data []byte
	Mime string
}

// AssetFetcher downloads a provider-returned asset URL so its bytes can be
// persisted. It is separate from the provider client: a provider may answer
// with a URL, and the adapter — not the model — decides whether to fetch it.
type AssetFetcher interface {
	Fetch(ctx context.Context, rawURL string) (FetchedAsset, error)
}

// HTTPFetcher is the default AssetFetcher. It never sends a credential: the
// URL came from the provider, and forwarding an Authorization header to an
// asset host would leak it.
type HTTPFetcher struct {
	Client   *http.Client
	MaxBytes int64
}

// DefaultAssetBytes bounds one downloaded asset (32 MiB). Providers that return
// larger originals are asked to use their base64 form or a smaller rendition.
const DefaultAssetBytes = 32 << 20

// NewHTTPFetcher returns a fetcher with a bounded client. A non-positive
// maxBytes uses DefaultAssetBytes.
func NewHTTPFetcher(maxBytes int64) *HTTPFetcher {
	if maxBytes <= 0 {
		maxBytes = DefaultAssetBytes
	}
	return &HTTPFetcher{
		MaxBytes: maxBytes,
		Client: &http.Client{
			Timeout: 2 * time.Minute,
			CheckRedirect: func(req *http.Request, via []*http.Request) error {
				if len(via) >= 5 {
					return errors.New("too many redirects")
				}
				if req.URL.Scheme != "http" && req.URL.Scheme != "https" {
					return fmt.Errorf("refusing redirect to scheme %q", req.URL.Scheme)
				}
				return nil
			},
		},
	}
}

// Fetch implements AssetFetcher.
func (f *HTTPFetcher) Fetch(ctx context.Context, rawURL string) (FetchedAsset, error) {
	if f == nil || f.Client == nil {
		return FetchedAsset{}, configError("artifact", "fetch", "asset fetcher is not configured")
	}
	parsed, err := url.Parse(strings.TrimSpace(rawURL))
	if err != nil || parsed.Host == "" || (parsed.Scheme != "http" && parsed.Scheme != "https") {
		return FetchedAsset{}, requestError("artifact", "fetch", "asset URL must be an absolute http(s) URL", []FieldError{{
			Field: "url", Message: "unsupported asset URL",
		}})
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, parsed.String(), nil)
	if err != nil {
		return FetchedAsset{}, artifactError("artifact", "fetch", err)
	}
	resp, err := f.Client.Do(req)
	if err != nil {
		return FetchedAsset{}, providerError("artifact", "fetch", err)
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		return FetchedAsset{}, upstreamError("artifact", "fetch", resp.StatusCode,
			fmt.Sprintf("asset host answered HTTP %d", resp.StatusCode), "")
	}
	limit := f.MaxBytes
	if limit <= 0 {
		limit = DefaultAssetBytes
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, limit+1))
	if err != nil {
		return FetchedAsset{}, providerError("artifact", "fetch", err)
	}
	if int64(len(data)) > limit {
		return FetchedAsset{}, &Error{
			Family:  "artifact",
			Op:      "fetch",
			Kind:    KindUpstream,
			Message: fmt.Sprintf("asset exceeds the %d-byte limit", limit),
		}
	}
	mime := strings.TrimSpace(strings.Split(resp.Header.Get("Content-Type"), ";")[0])
	if mime == "" {
		mime = http.DetectContentType(data)
	}
	return FetchedAsset{Data: data, Mime: mime}, nil
}

// BoundedHTTPClient is the shared provider client shape: no redirects (an
// Authorization header must not travel to another host) and a total timeout.
func BoundedHTTPClient(timeout time.Duration) *http.Client {
	if timeout <= 0 {
		timeout = 2 * time.Minute
	}
	return &http.Client{
		Timeout: timeout,
		CheckRedirect: func(*http.Request, []*http.Request) error {
			return http.ErrUseLastResponse
		},
		Transport: &http.Transport{
			Proxy:                 http.ProxyFromEnvironment,
			DialContext:           (&net.Dialer{Timeout: 15 * time.Second}).DialContext,
			TLSHandshakeTimeout:   15 * time.Second,
			ResponseHeaderTimeout: timeout,
		},
	}
}
