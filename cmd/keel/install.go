// `keel install`: register the single binary as a desktop app. macOS generates
// a real .app from the running binary and its embedded assets, ad-hoc signs it,
// and clears the download quarantine — no notarization, no external installer.
package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
)

func runInstallCmd(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("keel install", flag.ContinueOnError)
	fs.SetOutput(stderr)
	var (
		dir       = fs.String("dir", "", "parent directory for Keel.app (default ~/Applications)")
		noOpen    = fs.Bool("no-open", false, "do not open the app after installing")
		force     = fs.Bool("force", false, "replace an existing Keel.app")
		uninstall = fs.Bool("uninstall", false, "remove the installed app")
		purge     = fs.Bool("purge", false, "with --uninstall, also delete the local data")
	)
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *uninstall {
		return uninstallApp(*dir, *purge, stdout, stderr)
	}
	switch runtime.GOOS {
	case "darwin":
		return installMacApp(*dir, *noOpen, *force, stdout, stderr)
	case "windows":
		return installWindows(*noOpen, *force, stdout, stderr)
	default:
		fmt.Fprintf(stderr, "keel install: app registration is implemented for macOS/Windows in this build; run `keel start` on %s\n", runtime.GOOS)
		return 1
	}
}

const cliShimMarker = "# keel app shim"

func cliShimPath() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return filepath.Join(home, ".local", "bin", "keel")
}

// installCLIShim puts a small `keel` launcher on the conventional user bin
// path so an installed .app can still be updated (`keel update`) without the
// original download. It never replaces an unrelated file.
func installCLIShim(app string, stdout, stderr io.Writer) {
	path := cliShimPath()
	if path == "" {
		return
	}
	if fi, err := os.Lstat(path); err == nil && fi.Mode()&os.ModeSymlink != 0 {
		fmt.Fprintf(stderr, "keel install: %s is a symlink; left unchanged\n", path)
		return
	}
	if existing, err := os.ReadFile(path); err == nil && !strings.Contains(string(existing), cliShimMarker) {
		fmt.Fprintf(stderr, "keel install: %s exists and is not a keel shim; left unchanged\n", path)
		return
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		fmt.Fprintf(stderr, "keel install: cli shim: %v\n", err)
		return
	}
	script := "#!/bin/sh\n" + cliShimMarker + " (generated by keel install)\nexec " +
		shellQuote(filepath.Join(app, "Contents", "MacOS", "keel-bin")) + " \"$@\"\n"
	if err := os.WriteFile(path, []byte(script), 0o755); err != nil {
		fmt.Fprintf(stderr, "keel install: cli shim: %v\n", err)
		return
	}
	if err := os.Chmod(path, 0o755); err != nil {
		fmt.Fprintf(stderr, "keel install: cli shim: %v\n", err)
		return
	}
	if !pathHasDir(filepath.Dir(path)) {
		fmt.Fprintf(stdout, "cli: %s (add %s to PATH)\n", path, filepath.Dir(path))
	} else {
		fmt.Fprintf(stdout, "cli: %s\n", path)
	}
}

func pathHasDir(dir string) bool {
	for _, entry := range filepath.SplitList(os.Getenv("PATH")) {
		if entry == dir {
			return true
		}
	}
	return false
}

func removeCLIShim(stdout io.Writer) {
	path := cliShimPath()
	if path == "" {
		return
	}
	data, err := os.ReadFile(path)
	if err != nil || !strings.Contains(string(data), cliShimMarker) {
		return
	}
	if err := os.Remove(path); err == nil {
		fmt.Fprintf(stdout, "removed cli: %s\n", path)
	}
}

func defaultApplicationsDir() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, "Applications"), nil
}

func installMacApp(dir string, noOpen, force bool, stdout, stderr io.Writer) int {
	if dir == "" {
		var err error
		dir, err = defaultApplicationsDir()
		if err != nil {
			fmt.Fprintf(stderr, "keel install: %v\n", err)
			return 1
		}
	}
	app := filepath.Join(dir, "Keel.app")
	if _, err := os.Stat(app); err == nil && !force {
		fmt.Fprintf(stderr, "keel install: %s exists; pass --force to replace it\n", app)
		return 1
	}
	if !hasEmbeddedPG() {
		fmt.Fprintln(stderr, "keel install: this build has no bundled assets; download the self-contained release")
		return 1
	}
	runtimeDir, err := ensureRuntime(stderr)
	if err != nil {
		fmt.Fprintf(stderr, "keel install: %v\n", err)
		return 1
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fmt.Fprintf(stderr, "keel install: %v\n", err)
		return 1
	}
	if force {
		if err := os.RemoveAll(app); err != nil {
			fmt.Fprintf(stderr, "keel install: %v\n", err)
			return 1
		}
	}
	macOS := filepath.Join(app, "Contents", "MacOS")
	resources := filepath.Join(app, "Contents", "Resources")
	for _, path := range []string{macOS, resources} {
		if err := os.MkdirAll(path, 0o755); err != nil {
			fmt.Fprintf(stderr, "keel install: %v\n", err)
			return 1
		}
	}
	exe, err := os.Executable()
	if err != nil {
		fmt.Fprintf(stderr, "keel install: %v\n", err)
		return 1
	}
	if err := copyExecutable(exe, filepath.Join(macOS, "keel-bin")); err != nil {
		fmt.Fprintf(stderr, "keel install: %v\n", err)
		return 1
	}
	// CFBundleExecutable runs `keel start`: a bare `keel` is the CLI, and the
	// app's double-click has no arguments to tell it otherwise.
	launcher := "#!/bin/sh\nexec \"$(dirname \"$0\")/keel-bin\" start \"$@\"\n"
	if err := os.WriteFile(filepath.Join(macOS, "Keel"), []byte(launcher), 0o755); err != nil {
		fmt.Fprintf(stderr, "keel install: %v\n", err)
		return 1
	}
	if err := copyTree(filepath.Join(runtimeDir, "pg"), filepath.Join(resources, "pg")); err != nil {
		fmt.Fprintf(stderr, "keel install: %v\n", err)
		return 1
	}
	if err := copyTree(filepath.Join(runtimeDir, "web"), filepath.Join(resources, "web")); err != nil {
		fmt.Fprintf(stderr, "keel install: %v\n", err)
		return 1
	}
	_ = copyFileIfExists(filepath.Join(runtimeDir, "icon.png"), filepath.Join(resources, "icon.png"))
	_ = copyFileIfExists(filepath.Join(runtimeDir, "README.md"), filepath.Join(resources, "README.md"))
	if err := os.WriteFile(filepath.Join(app, "Contents", "Info.plist"), []byte(infoPlist()), 0o644); err != nil {
		fmt.Fprintf(stderr, "keel install: %v\n", err)
		return 1
	}
	signApp(app, stderr)
	// The source binary may carry the browser's download quarantine; the app is
	// generated locally, so clear it before the first open.
	_ = exec.Command("xattr", "-dr", "com.apple.quarantine", app).Run()
	installCLIShim(app, stdout, stderr)
	fmt.Fprintf(stdout, "installed: %s\n", app)
	if !noOpen {
		if err := exec.Command("open", app).Run(); err != nil {
			fmt.Fprintf(stderr, "keel install: open %s: %v\n", app, err)
		}
	}
	return 0
}

func uninstallApp(dir string, purge bool, stdout, stderr io.Writer) int {
	if runtime.GOOS == "windows" {
		return uninstallWindows(purge, stdout, stderr)
	}
	if dir == "" {
		var err error
		dir, err = defaultApplicationsDir()
		if err != nil {
			fmt.Fprintf(stderr, "keel uninstall: %v\n", err)
			return 1
		}
	}
	app := filepath.Join(dir, "Keel.app")
	if err := os.RemoveAll(app); err != nil {
		fmt.Fprintf(stderr, "keel uninstall: %v\n", err)
		return 1
	}
	removeCLIShim(stdout)
	fmt.Fprintf(stdout, "removed: %s\n", app)
	if purge {
		if home := keelHome(); home != "" {
			if err := os.RemoveAll(home); err != nil {
				fmt.Fprintf(stderr, "keel uninstall: %v\n", err)
				return 1
			}
			fmt.Fprintf(stdout, "removed data: %s\n", home)
		}
	} else {
		fmt.Fprintln(stdout, "local data kept; pass --purge to remove it")
	}
	return 0
}

func windowsInstallDir() (string, error) {
	local := os.Getenv("LOCALAPPDATA")
	if local == "" {
		return "", errors.New("LOCALAPPDATA is not set")
	}
	return filepath.Join(local, "Keel"), nil
}

func windowsShortcutPath() string {
	appData := os.Getenv("APPDATA")
	if appData == "" {
		return ""
	}
	return filepath.Join(appData, "Microsoft", "Windows", "Start Menu", "Programs", "Keel.lnk")
}

// installWindows registers the app for the current user: no administrator
// prompt, no machine-wide writes. The registry key is HKCU\Software\Classes.
func installWindows(noOpen, force bool, stdout, stderr io.Writer) int {
	dir, err := windowsInstallDir()
	if err != nil {
		fmt.Fprintf(stderr, "keel install: %v\n", err)
		return 1
	}
	target := filepath.Join(dir, "keel.exe")
	exe, err := os.Executable()
	if err != nil {
		fmt.Fprintf(stderr, "keel install: %v\n", err)
		return 1
	}
	same := strings.EqualFold(filepath.Clean(exe), filepath.Clean(target))
	if _, err := os.Stat(target); err == nil && !force && !same {
		fmt.Fprintf(stderr, "keel install: %s exists; pass --force to replace it\n", target)
		return 1
	}
	if !same {
		if !hasEmbeddedPG() {
			fmt.Fprintln(stderr, "keel install: this build has no bundled assets; download the self-contained release")
			return 1
		}
		runtimeDir, err := ensureRuntime(stderr)
		if err != nil {
			fmt.Fprintf(stderr, "keel install: %v\n", err)
			return 1
		}
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fmt.Fprintf(stderr, "keel install: %v\n", err)
			return 1
		}
		if err := copyExecutable(exe, target); err != nil {
			fmt.Fprintf(stderr, "keel install: %v\n", err)
			return 1
		}
		// The binary already embeds the runtime; the first `start` extracts it
		// under %USERPROFILE%\.keel. Copying the PG tree here would duplicate
		// 300 MB and hit Windows symlink privileges.
		_ = copyFileIfExists(filepath.Join(runtimeDir, "README.md"), filepath.Join(dir, "README.md"))
	}
	if err := registerWindowsScheme(target); err != nil {
		fmt.Fprintf(stderr, "keel install: registry: %v\n", err)
		return 1
	}
	createWindowsShortcut(target, stderr)
	fmt.Fprintf(stdout, "installed: %s\n", dir)
	if !noOpen {
		_ = exec.Command("cmd", "/c", "start", "", target).Run()
	}
	return 0
}

func registerWindowsScheme(target string) error {
	command := fmt.Sprintf("\"%s\" start \"%%1\"", target)
	steps := [][]string{
		{"reg", "add", `HKCU\Software\Classes\keel`, "/ve", "/d", "URL:Keel", "/f"},
		{"reg", "add", `HKCU\Software\Classes\keel`, "/v", "URL Protocol", "/d", "", "/f"},
		{"reg", "add", `HKCU\Software\Classes\keel\shell\open\command`, "/ve", "/d", command, "/f"},
	}
	for _, step := range steps {
		if out, err := exec.Command(step[0], step[1:]...).CombinedOutput(); err != nil {
			return fmt.Errorf("%v: %s", err, strings.TrimSpace(string(out)))
		}
	}
	return nil
}

func createWindowsShortcut(target string, stderr io.Writer) {
	shortcut := windowsShortcutPath()
	if shortcut == "" {
		return
	}
	script := fmt.Sprintf(`$s=(New-Object -ComObject WScript.Shell).CreateShortcut('%s'); $s.TargetPath='%s'; $s.Arguments='start'; $s.Save()`, strings.ReplaceAll(shortcut, "'", "''"), strings.ReplaceAll(target, "'", "''"))
	_ = exec.Command("powershell", "-NoProfile", "-NonInteractive", "-Command", script).Run()
}

func uninstallWindows(purge bool, stdout, stderr io.Writer) int {
	dir, err := windowsInstallDir()
	if err != nil {
		fmt.Fprintf(stderr, "keel uninstall: %v\n", err)
		return 1
	}
	_ = exec.Command("reg", "delete", `HKCU\Software\Classes\keel`, "/f").Run()
	if shortcut := windowsShortcutPath(); shortcut != "" {
		_ = os.Remove(shortcut)
	}
	if err := os.RemoveAll(dir); err != nil {
		fmt.Fprintf(stderr, "keel uninstall: %v\n", err)
		return 1
	}
	fmt.Fprintf(stdout, "removed: %s\n", dir)
	if purge {
		if home := keelHome(); home != "" {
			_ = os.RemoveAll(home)
			fmt.Fprintf(stdout, "removed data: %s\n", home)
		}
	}
	return 0
}

func copyExecutable(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(dst, data, 0o755); err != nil {
		return err
	}
	return os.Chmod(dst, 0o755)
}

func copyFileIfExists(src, dst string) error {
	data, err := os.ReadFile(src)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	return os.WriteFile(dst, data, 0o644)
}

func signApp(app string, stderr io.Writer) {
	if _, err := exec.LookPath("codesign"); err != nil {
		fmt.Fprintln(stderr, "keel install: codesign not found; the app is unsigned")
		return
	}
	out, err := exec.Command("codesign", "--force", "--deep", "--sign", "-", app).CombinedOutput()
	if err != nil {
		fmt.Fprintf(stderr, "keel install: ad-hoc codesign failed: %v\n%s\n", err, strings.TrimSpace(string(out)))
	}
}

