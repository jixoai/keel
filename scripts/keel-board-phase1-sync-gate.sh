#!/usr/bin/env bash
# Phase 1 sync/secrets evidence for keel-board-v1 (tasks 10.6, 12.1-12.4,
# 13.1-13.2).
#
# Generates openspec/changes/keel-board-v1/evidence/phase-1-sync.md and the
# E2E HTML report beside it. The markdown is command output, never hand-written.
#
# Usage:
#   KEEL_TEST_DSN='postgres://…' scripts/keel-board-phase1-sync-gate.sh
#   KEEL_BOARD_BASE=a088058 KEEL_TEST_DSN=… scripts/keel-board-phase1-sync-gate.sh
#
# The DSN must point at a dedicated test database: the real-PostgreSQL suites
# create tenants and a throwaway board schema, and the E2E drops its schema.
set -euo pipefail

repo_root="$(git rev-parse --show-toplevel)"
evidence_dir="$repo_root/openspec/changes/keel-board-v1/evidence"
evidence="$evidence_dir/phase-1-sync.md"
e2e_html="$evidence_dir/phase-1-sync-e2e.html"
base_ref="${KEEL_BOARD_BASE:-6ee7fe3}"
budget_kb="${KEEL_BOARD_BINARY_BUDGET_KB:-4096}"
if [ -z "${KEEL_TEST_DSN:-}" ]; then
  echo "keel-board-phase1-sync-gate: KEEL_TEST_DSN is required for the real-PostgreSQL suites" >&2
  exit 2
fi
mkdir -p "$evidence_dir"
cd "$repo_root"

section() { printf '\n## %s\n\n' "$1" >>"$evidence"; }
gate_failed=0
# block records a command's output and exit status without aborting the rest of
# the evidence run: a failing gate must be visible in the report, not stop it.
block() {
  local status
  {
    printf '```text\n'
    set +e
    "$@"
    status=$?
    set -e
    printf '```\n'
    printf 'exit=%d\n' "$status"
  } >>"$evidence" 2>&1
  if [ "$status" -ne 0 ]; then
    gate_failed=1
  fi
  return 0
}

cat >"$evidence" <<EOF
# Phase 1 sync/secrets evidence (keel-board-v1 10.6, 12.1-12.4, 13.1-13.2)

Generated by \`scripts/keel-board-phase1-sync-gate.sh\` on $(date -u '+%Y-%m-%dT%H:%M:%SZ').
This file is script output, not hand-written.

- board module: $(go list -m -f '{{.Path}} {{.Version}}' github.com/jixoai/keel-board)
- go: $(go version)
- keel baseline for the binary-size delta: \`$base_ref\`
- E2E HTML report: [phase-1-sync-e2e.html](phase-1-sync-e2e.html)
EOF

section "10.6 tenant flags, secret resolver, entry management"
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test ./internal/boardintegration/ -run 'TestBoardFlagMatrix|TestSyncEntryAdminRoutes|TestParseBoardFlagsMatrix|TestBoardSyncPath|TestAutomationSurfaceAndWorkersMount' -count=1 -v
block go test ./internal/host/ -run 'TestBoardTenantConfig' -count=1 -v

section "12.1-12.4 full board integration suite (real PostgreSQL)"
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test ./internal/boardintegration/ -count=1 -v

section "Race detector (board integration)"
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test -race ./internal/boardintegration/ -count=1

section "13.1 repository-wide unit/integration suite (CI runs -p 1)"
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test -p 1 ./... -count=1

section "13.1 keel-board v0.1.1 conformance (module dependency, not copied)"
block env KEEL_BOARD_TEST_DSN="$KEEL_TEST_DSN" go test github.com/jixoai/keel-board/conformance -count=1

section "13.2 sync E2E: fake Slack/GitHub/Linear/Chat SDK bridge on real PostgreSQL"
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go run ./cmd/board-sync-e2e -dsn "$KEEL_TEST_DSN" -out "$e2e_html"

section "Format and vet"
block sh -c 'test -z "$(gofmt -l .)" || { gofmt -l .; exit 1; }'
block go vet ./internal/boardintegration/ ./internal/store/ ./internal/host/ ./cmd/keel/ ./cmd/board-sync-e2e/

section "Binary size (keel + runtime, linux/amd64+arm64; budget $budget_kb KiB)"
printf 'The foundation budget is %s KiB per binary and target (checked-in CI uses the same value).\n' "$budget_kb" >>"$evidence"
printf 'The delta is measured against the rebased foundation HEAD.\n\n' >>"$evidence"
block scripts/binary-size.sh --budget-kb "$budget_kb" --base "$base_ref"

printf '\nEvidence written to %s\n' "$evidence"
printf 'E2E report written to %s\n' "$e2e_html"
exit "$gate_failed"
