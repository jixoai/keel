#!/usr/bin/env bash
# Phase 1 infrastructure evidence for keel-board-v1 (tasks 10.1-10.5, 10.7).
#
# Generates openspec/changes/keel-board-v1/evidence/phase-1-infrastructure.md
# from real command output. The real-PostgreSQL suite needs KEEL_TEST_DSN to
# point at a dedicated test database (it creates and drops a throwaway board
# schema; keel's own tables use fresh tenant UUIDs).
#
# Usage:
#   KEEL_TEST_DSN='postgres://…' scripts/keel-board-phase1-gate.sh
#   KEEL_BOARD_BASE=6ee7fe3 KEEL_TEST_DSN=… scripts/keel-board-phase1-gate.sh
set -euo pipefail

repo_root="$(git rev-parse --show-toplevel)"
evidence="$repo_root/openspec/changes/keel-board-v1/evidence/phase-1-infrastructure.md"
base_ref="${KEEL_BOARD_BASE:-6ee7fe3}"
if [ -z "${KEEL_TEST_DSN:-}" ]; then
  echo "keel-board-phase1-gate: KEEL_TEST_DSN is required for the real-PostgreSQL suites" >&2
  exit 2
fi
mkdir -p "$(dirname "$evidence")"
cd "$repo_root"
failures=0

section() { printf '\n## %s\n\n' "$1" >>"$evidence"; }
# block records a command's output and exit status without aborting the rest of
# the evidence run. A failing command (a test, vet, or the binary-size budget)
# must be visible in the report, and the script exits non-zero at the end: an
# evidence generator that always returns 0 is not a gate.
block() {
  local status
  {
    printf '```text\n'
    set +e
    "$@"
    status=$?
    set -e
    printf '```\n'
    printf 'exit=%d\n' "$status"
  } >>"$evidence" 2>&1
  if [ "$status" -ne 0 ]; then
    failures=$((failures + 1))
  fi
}

cat >"$evidence" <<EOF
# Phase 1 infrastructure evidence (keel-board-v1 10.1-10.5, 10.7)

Generated by \`scripts/keel-board-phase1-gate.sh\` on $(date -u '+%Y-%m-%dT%H:%M:%SZ').
This file is script output, not hand-written.

- board module: $(go list -m -f '{{.Path}} {{.Version}}' github.com/jixoai/keel-board)
- go: $(go version)
- keel baseline for the binary-size gate: \`$base_ref\`
EOF

section "10.1 Pin and module"
block go list -m -f '{{.Path}} {{.Version}}' github.com/jixoai/keel-board
block grep -n 'github.com/jixoai/keel-board' go.mod go.sum
block grep -n 'keel-board' NOTICE README.md docs/RUNBOOK.md

section "10.2-10.5, 10.7 adapter + real PostgreSQL"
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test ./internal/boardintegration/ -count=1 -v
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test -race ./internal/boardintegration/ -count=1

section "RBAC key registry and route gate"
block go test ./internal/access/ ./internal/accessgate/ ./cmd/keel/ -count=1

section "Repository-wide unit/integration suite (CI runs -p 1)"
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test -p 1 ./... -count=1

section "Format and vet"
block sh -c 'test -z "$(gofmt -l .)" || { gofmt -l .; exit 1; }'
block go vet ./...

section "Binary size (keel + runtime, linux/amd64+arm64, 3072 KiB budget)"
block scripts/binary-size.sh --budget-kb 3072 --base "$base_ref"

if [ "$failures" -ne 0 ]; then
  printf 'keel-board-phase1-gate: %d command(s) failed; see %s\n' "$failures" "$evidence" >&2
  exit 1
fi
printf '\nEvidence written to %s\n' "$evidence"
