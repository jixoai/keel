#!/usr/bin/env bash
# Phase 1 superagent evidence for keel-board-v1 (tasks 11.1-11.6).
#
# Generates openspec/changes/keel-board-v1/evidence/phase-1-superagent.md from
# real command output. The real-PostgreSQL suites need KEEL_TEST_DSN pointing at
# a dedicated test database (throwaway board schemas + fresh tenant UUIDs).
#
# Usage:
#   KEEL_TEST_DSN='postgres://…' scripts/keel-board-phase1-superagent-gate.sh
#   KEEL_BOARD_BASE=a088058 KEEL_TEST_DSN=… scripts/keel-board-phase1-superagent-gate.sh
set -euo pipefail

repo_root="$(git rev-parse --show-toplevel)"
evidence="$repo_root/openspec/changes/keel-board-v1/evidence/phase-1-superagent.md"
base_ref="${KEEL_BOARD_BASE:-6ee7fe3}"
if [ -z "${KEEL_TEST_DSN:-}" ]; then
  echo "keel-board-phase1-superagent-gate: KEEL_TEST_DSN is required for the real-PostgreSQL suites" >&2
  exit 2
fi
mkdir -p "$(dirname "$evidence")"
cd "$repo_root"

section() { printf '\n## %s\n\n' "$1" >>"$evidence"; }
failures=0
# block records a command's output and exit status without aborting the rest of
# the evidence run. Any failing block makes the script exit non-zero: an
# evidence generator that always returns 0 is not a gate.
block() {
  local status
  {
    printf '```text\n'
    set +e
    "$@"
    status=$?
    set -e
    printf '```\n'
    printf 'exit=%d\n' "$status"
  } >>"$evidence" 2>&1
  if [ "$status" -ne 0 ]; then
    failures=$((failures + 1))
  fi
  return 0
}

cat >"$evidence" <<EOF
# Phase 1 superagent evidence (keel-board-v1 11.1-11.6)

Generated by \`scripts/keel-board-phase1-superagent-gate.sh\` on $(date -u '+%Y-%m-%dT%H:%M:%SZ').
This file is script output, not hand-written.

- board module: $(go list -m -f '{{.Path}} {{.Version}}' github.com/jixoai/keel-board)
- go: $(go version)
- binary-size baseline: \`$base_ref\` (4096 KiB budget per binary and target)
EOF

section "11.1 board_links, tenant switches, switch matrix"
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test ./internal/store/ -run 'TestBoardLinks' -count=1 -v
block go test ./internal/superagentboard/ -run 'TestSwitchMatrix|TestParseDocument|TestTokenSource|TestClaimToken' -count=1 -v

section "11.2 Ticket->task, Assignment->claim, lease renewal, restart"
block go test ./internal/superagentboard/ -run 'TestEnsureTicketThread|TestClaimRenew|TestMirrorTicket|TestMirrorClaim|TestMirrorDoesNotOverride|TestMirrorReopens' -count=1 -v
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test ./internal/superagentboard/ -run 'TestPGBoard' -count=1 -v

section "11.3 Attention->blocked/unblock, report->reply, idempotency"
block go test ./internal/superagentboard/ -run 'TestMirrorAttention|TestMirrorReport|TestMirrorSkips|TestMirrorGitHub|TestMirrorNeverRewrites|TestMirrorLogs|TestMirrorTimedOut|TestMirrorCompleted|TestMirrorCounts|TestMirrorReopens' -count=1 -v

section "11.4 command bridge: all actions, rejection, timeout, task.write gate"
block go test ./internal/superagentboard/ -run 'TestBridge|TestStaleLink' -count=1 -v

section "11.5/11.6 single task surface + frozen legacy board"
block go test ./internal/superagentboard/ -run 'TestBoardCarriesTheTicketAnswerCompletionJourney' -count=1 -v

section "Touched packages, real PostgreSQL + race"
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test -p 1 ./internal/store/ ./internal/superagent/ ./internal/boardintegration/ ./internal/superagentboard/ ./cmd/keel/ -count=1
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test -race ./internal/superagentboard/ -count=1
block env KEEL_TEST_DSN="$KEEL_TEST_DSN" go test -race ./internal/store/ -run 'TestBoardLinks' -count=1

section "Mutation gate (4 targeted mutations must be red)"
block scripts/keel-board-phase1-superagent-mutations.sh

section "Format and vet"
block sh -c 'test -z "$(gofmt -l internal cmd)" || { gofmt -l internal cmd; exit 1; }'
block go vet ./internal/superagentboard/ ./internal/store/ ./internal/superagent/ ./cmd/keel/

section "Binary size (keel + runtime, linux/amd64+arm64; budget 4096 KiB)"
block scripts/binary-size.sh --budget-kb 4096 --base "$base_ref"

if [ "$failures" -ne 0 ]; then
  printf 'keel-board-phase1-superagent-gate: %d command(s) failed; see %s\n' "$failures" "$evidence" >&2
  exit 1
fi
printf '\nEvidence written to %s\n' "$evidence"
